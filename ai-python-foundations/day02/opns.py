#arithmetic operators
a = 10
b = 3
print(a + b) #addition 
print(a - b) #subtraction
print(a * b) #multiplication
print(a / b) #division
print(a % b) #modulus   

#comparison operators
print(a > b) #greater than
print(a < b) #less than
print(a == b) #equal to 

#logical operators
print(a and b) #logical and
print(a or b) #logical or
print(not a) #logical not