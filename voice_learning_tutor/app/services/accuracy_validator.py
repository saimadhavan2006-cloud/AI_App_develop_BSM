
import re


def validate_8051_answer(
    answer: str,
    question: str = "",
) -> list[str]:
    """Detect known accuracy issues in classic 8051 explanations."""
    text = re.sub(r"\s+", " ", answer.lower())
    issues = []

    # Timer 0 is identified by T0, not TO.
    if (
        re.search(r"\btimer\s*0\s*(?:is\s*)?to\b", text)
        or re.search(r"\btimers?\s+(?:are\s+)?to\s+and\s+t1\b", text)
    ):
        issues.append("Use T0 for Timer 0, not TO.")

    # Classic 8051 has 128 bytes of internal RAM.

    # Classic 8051 has 128 bytes of internal RAM.
    has_internal_ram = bool(
        re.search(
            r"\b128\s*[- ]?bytes?\b.{0,60}\binternal\s+ram\b",
            text,
        )
        or re.search(
            r"\binternal\s+ram\b.{0,60}\b128\s*[- ]?bytes?\b",
            text,
        )
        or re.search(
            r"\b128\s*[- ]?bytes?\s+of\s+(?:internal\s+)?"
            r"(?:data\s+)?ram\b",
            text,
        )
    )

    if not has_internal_ram:
        issues.append(
            "Verify the classic 8051's 128-byte internal RAM."
        )


    # Require program ROM facts only when the question asks about them,
    # or when no specific question was supplied (legacy behavior).
    rom_question = bool(
        re.search(
            r"\b(?:rom|program memory|program storage|code memory)\b",
            question.lower(),
        )
    )

    if not question.strip() or rom_question:
        if not re.search(
            r"\b(?:4\s*kb|4k\s+bytes|4096\s+bytes)\b",
            text,
        ):
            issues.append(
                "Verify the classic 8051's 4 KB on-chip program ROM."
            )

    # Harvard architecture uses separate code and data address spaces.
    if "same address space for code and data" in text:
        issues.append(
            "Harvard architecture uses separate code and data address spaces."
        )

    # INT0 and INT1 are external interrupt inputs.
    if re.search(
        r"\bint[01]\s*:\s*generated by internal chip operations\b", text
    ):
        issues.append("INT0 and INT1 are external interrupt inputs.")

    # Classic 8051 has five interrupt vectors.
    # Some descriptions count the serial receive and transmit
    # interrupt conditions separately, producing six requests.
    if re.search(
        r"\b(?:6|six)\s+interrupt\s+(?:sources|vectors)\b",
        text,
    ):
        issues.append(
            "Clarify the interrupt-counting convention: the classic 8051 "
            "has five interrupt vectors; serial receive and transmit "
            "conditions may be counted separately."
        )

    # Avoid confusing RAM, SFRs, and general-purpose memory.
    if (
        "128 bytes of special function register memory" in text
        or "128 bytes of sfr ram" in text
        or "32 general-purpose data memory" in text
    ):
        issues.append(
            "Correct the SFR/general-purpose RAM description; "
            "do not treat these as additional memory."
        )

    # Flag misleading textbook-style ROM ranges.
    if re.search(
        r"internal rom or eprom"
        r"(?:\s*\([^)]*\))?"
        r"\s*(?:of\s*)?0\s+to\s+4\s*"
        r"(?:k|kb|kbytes|kilobytes)\b",
        text,
    ):
        issues.append(
            "For the classic 8051, state 4 KB of on-chip program ROM; "
            "describe variants separately."
        )

    # The 16-byte bit-addressable area is not total general-purpose RAM.
    if re.search(
        r"(?:sixteen|16)\s+bytes?\s+of\s+general-purpose\s+data\s+memory",
        text,
    ):
        issues.append(
            "Do not describe the 16-byte bit-addressable area as "
            "the total general-purpose data memory."
        )

    # Classic 8051 has 128 bytes of internal RAM, not 80 bytes total.
    if re.search(
        r"\b80\s+bytes?\s+of\s+general-purpose\s+(?:internal\s+)?"
        r"(?:data\s+)?ram\b",
        text,
    ):
        issues.append(
            "The classic 8051 has 128 bytes of internal RAM; "
            "do not mislabel 80 bytes as its total general-purpose RAM."
        )


    # Program Counter is 16-bit.
    # Detect an explicit claim that PC is 8-bit without confusing
    # "8051 is an 8-bit microcontroller" with the PC width.
    pc_text = answer.lower()

    wrong_pc_patterns = [
        r"\b(?:program counter|pc)\s*(?:\(\s*pc\s*\))?"
        r"\s*(?:is|has|of)\s+(?:an?\s+)?8\s*-?\s*bit\b",
        r"\b8\s*-?\s*bit\s+(?:program counter|pc)\b",
    ]

    for pattern in wrong_pc_patterns:
        if re.search(pattern, pc_text):
            issues.append(
                "The classic 8051 Program Counter (PC) is 16-bit."
            )
            break



    if re.search(
        r"(?:\bpsw\b|\bprogram status word\b)"
        r".{0,35}\b16\s*[- ]?bit\b"
        r"|\b16\s*[- ]?bit\b.{0,35}(?:\bpsw\b|\bprogram status word\b)",
        text,
    ):
        issues.append("The classic 8051 PSW (Program Status Word) is 8-bit.")



    # Internal RAM and SFR address-space confusion.
    if re.search(
        r"(?:ram|internal data memory).{0,100}"
        r"(?:part of|within|inside)\s+(?:the\s+)?"
        r"sfr\s+(?:address\s+)?space",
        text,
    ):
        issues.append(
            "Internal RAM and SFRs occupy distinct address ranges "
            "in the classic 8051."
        )

    # Check RAM layout independently when the question asks about it.

    # Validate RAM layout only when the question asks about it.
    ram_layout_question = bool(
        re.search(
            r"\b(?:ram layout|ram organization|address map|memory map)\b",
            question.lower(),
        )
    )

    if ram_layout_question:
        required_regions = [
            (
                r"\bregister banks?\b.*?\b00h\s*[-â€“â€”]\s*1fh\b",
                "The register banks occupy addresses 00Hâ€“1FH.",
            ),
            (
                r"\bbit.addressable ram\b.*?\b20h\s*[-â€“â€”]\s*2fh\b",
                "Bit-addressable RAM occupies addresses 20Hâ€“2FH.",
            ),
            (
                r"\bgeneral.purpose ram\b.*?\b30h\s*[-â€“â€”]\s*7fh\b",
                "General-purpose RAM occupies addresses 30Hâ€“7FH.",
            ),
        ]

        for pattern, message in required_regions:
            if not re.search(pattern, text):
                issues.append(
                    "Check the classic 8051 RAM layout: " + message
                )



    # Flag incorrect claims about the 8051's 384-byte memory capacity.
    if re.search(
        r"(?:accommodate|contains|has|provides)\s+"
        r"384\s+bytes",
        text,
    ):
        issues.append(
            "Do not describe 384 bytes as the classic 8051's "
            "internal RAM capacity."
        )

    # Flag claims that the 8051's internal RAM is not directly accessible.
    if re.search(
        r"internal ram.{0,60}"
        r"(?:not directly accessible|cannot be directly accessed)",
        text,
    ):
        issues.append(
            "Correct the claim about internal RAM accessibility."
        )

    # Flag unsupported confusion between 8051 and 8057.
    if re.search(r"\b8057\b", text):
        issues.append(
            "Remove unrelated 8057 claims unless explicitly supported "
            "and relevant to the question."
        )


    # The classic 8051 does not split internal RAM into 64-byte
    # data and 64-byte program-code halves.
    if re.search(
        r"(?:lower|first)\s+64\s+bytes?.{0,100}"
        r"(?:upper|remaining)\s+64\s+bytes?",
        text,
    ) and re.search(
        r"upper\s+64\s+bytes?.{0,100}"
        r"(?:program\s+code|program\s+memory)",
        text,
    ):
        issues.append(
            "Incorrect RAM split: classic 8051 internal RAM is "
            "128 bytes at 00Hâ€“7FH, not a 64-byte data/code split."
        )


    # Internal RAM must not be described as program-code storage.
    if re.search(
        r"(?:upper|lower)\s+\d+\s+bytes?.{0,100}"
        r"(?:used for|store|storing|reserved for)\s+"
        r"(?:storing\s+)?program\s+code",
        text,
    ):
        issues.append(
            "Internal RAM stores data, not program code. "
            "Correct the RAM organization."
        )


    # Stronger classic 8051 internal RAM consistency checks.
    # The three regions are consecutive parts of the same 128-byte RAM.

    compact = re.sub(r"\s+", " ", text).replace("â€“", "-").replace("â€”", "-")

    ram_is_relevant = bool(
        re.search(r"\b(?:8051|internal ram|ram layout|ram organization)\b", compact)
        or re.search(r"\b(?:register banks|bit-addressable ram|general-purpose ram)\b", compact)
    )

    if ram_is_relevant:
        # Detect an incorrect total internal RAM capacity.
        wrong_total_patterns = [
            r"\b(?:internal ram|ram capacity|total ram)\b.{0,50}\b(?:64|256|384)\s+bytes?\b",
            r"\b(?:64|256|384)\s+bytes?\b.{0,50}\b(?:internal ram|total ram)\b",
        ]

        if any(re.search(pattern, compact) for pattern in wrong_total_patterns):
            issues.append(
                "The classic 8051 has 128 bytes of internal RAM. "
                "Do not confuse it with external RAM or variant-specific memory."
            )

        # Detect the false idea that the three regions are extra RAM.
        additive_region_claim = re.search(
            r"\b(?:additional|extra|another)\s+"
            r"(?:32|16|80)\s+bytes?\b.{0,100}"
            r"\b(?:register banks|bit.addressable|general.purpose)\b",
            compact,
        )
        if additive_region_claim:
            issues.append(
                "The register-bank, bit-addressable, and general-purpose "
                "regions are subdivisions of the same 128-byte internal RAM, "
                "not additional memory."
            )

        # Check region sizes when the answer explicitly associates a size
        # with a region.
        region_size_checks = [
            (
                r"\bregister banks?\s+(?:occupy|use|contain|are)\s+"
                r"(?:16|8)\s+bytes?\b",
                "The four register banks together occupy 32 bytes (00Hâ€“1FH).",
            ),
            (
                r"\bbit.addressable(?: ram)?\s+"
                r"(?:occupies|uses|contains|is)\s+"
                r"(?:8|32|80)\s+bytes?\b",
                "The bit-addressable RAM region occupies 16 bytes (20Hâ€“2FH).",
            ),
            (
                r"\bgeneral.purpose(?: ram)?\s+"
                r"(?:occupies|uses|contains|is)\s+"
                r"(?:16|32|64)\s+bytes?\b",
                "General-purpose RAM occupies 80 bytes (30Hâ€“7FH).",
            ),
        ]

        for pattern, message in region_size_checks:
            if re.search(pattern, compact):
                issues.append(message)

        # If the answer gives the standard region sizes, make sure it
        # explicitly describes them as subdivisions of internal RAM.
        mentions_all_regions = all(
            re.search(pattern, compact)
            for pattern in [
                r"\b32\s+bytes?\b",
                r"\b16\s+bytes?\b",
                r"\b80\s+bytes?\b",
            ]
        )

        describes_128_bytes = bool(
            re.search(r"\b128\s*[- ]?bytes?\b.{0,60}\binternal ram\b", compact)
            or re.search(r"\binternal ram\b.{0,60}\b128\s*[- ]?bytes?\b", compact)
        )

        if mentions_all_regions and describes_128_bytes:
            # This is a consistency check: don't reject correct descriptions
            # merely because they list the three region sizes separately.
            # The answer must not explicitly claim their sum exceeds 128.
            if re.search(
                r"\b(?:total|altogether|in addition to)\b.{0,40}"
                r"\b(?:160|208|256|384)\s+bytes?\b",
                compact,
            ):
                issues.append(
                    "The three RAM regions total 128 bytes, not a larger "
                    "combined internal RAM capacity."
                )

    # Avoid repeated identical validator messages from overlapping rules.
    issues = list(dict.fromkeys(issues))

    return issues
